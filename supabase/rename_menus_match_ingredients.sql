-- เปลี่ยน 4 เมนู (อ้างด้วย id คงที่ของ seed_master.sql + ชื่อเดิม — ถ้าชื่อถูกแก้ไปแล้วจะข้าม ไม่ทับ):
--   หมูสามชั้นย่าง                   → หมูสามชั้น
--   เต้าหู้ปลาทอด                    → เต้าหู้ปลา
--   เกี๊ยวกุ้งทอด                     → เกี๊ยวกุ้ง
--   เนื้อวากิวพรีเมียม (สั่งเพิ่ม)       → เนื้อวากิว   (ป้าย "สั่งเพิ่ม" แสดงจากราคาสั่งเพิ่มอยู่แล้ว)
--
-- ผลกระทบ: ชื่อใหม่ขึ้นทุกหน้า (หน้าลูกค้า, จอครัว, รายงานเมนูขายดี รวมของย้อนหลัง)
--   ใบเสร็จที่ออกไปแล้วไม่เปลี่ยน (bill_items เก็บชื่อตอนออกบิล)
-- รันซ้ำได้ · ไม่ลบข้อมูล
-- ============================================================

BEGIN;

UPDATE menu_items AS menu
SET name = rename.new_name
FROM (VALUES
    ('50000000-0000-4000-8000-000000000003'::uuid, 'หมูสามชั้นย่าง',                'หมูสามชั้น'),
    ('50000000-0000-4000-8000-000000000010'::uuid, 'เต้าหู้ปลาทอด',                 'เต้าหู้ปลา'),
    ('50000000-0000-4000-8000-000000000011'::uuid, 'เกี๊ยวกุ้งทอด',                  'เกี๊ยวกุ้ง'),
    ('50000000-0000-4000-8000-000000000005'::uuid, 'เนื้อวากิวพรีเมียม (สั่งเพิ่ม)',  'เนื้อวากิว')
) AS rename(id, old_name, new_name)
WHERE menu.id = rename.id
  AND menu.name = rename.old_name;

-- ตรวจผล: ต้องเห็นชื่อใหม่ทั้ง 4 แถว
SELECT id, name FROM menu_items
WHERE id IN ('50000000-0000-4000-8000-000000000003', '50000000-0000-4000-8000-000000000010',
             '50000000-0000-4000-8000-000000000011', '50000000-0000-4000-8000-000000000005')
ORDER BY name;

COMMIT;
